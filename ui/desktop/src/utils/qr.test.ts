const render = (modules: boolean[][]): string[] =>
  modules.map((row) => row.map((cell) => (cell ? '#' : '.')).join(''));

describe('qr', () => {
  it('encodes a short URL as version 1', () => {
    const code = qr('http://a');
    expect(code.size).toBe(21);
    expect(code.mask).toBe(2);
    expect(render(code.modules)).toEqual(SHORT);
  });

  it('encodes the phone URL with its 64-hex key as version 6', () => {
    const code = qr(PHONE);
    expect(code.size).toBe(41);
    expect(code.mask).toBe(2);
    expect(render(code.modules)).toEqual(PHONE_URL);
  });

  it('changes with the input', () => {
    expect(render(qr('http://a').modules)).not.toEqual(render(qr('http://b').modules));
  });

  it('refuses text past version 10', () => {
    expect(() => qr('x'.repeat(300))).toThrow(/version 10/);
  });
});

describe('qrSvg', () => {
  it('draws one unit square per dark module inside a four-module quiet zone', () => {
    const code = qr('http://a');
    const svg = qrSvg(code);
    expect(svg.viewBox).toBe('0 0 29 29');
    expect(svg.path.startsWith('M4 4h1v1h-1z')).toBe(true);
    const dark = code.modules.flat().filter(Boolean).length;
    expect(svg.path.split('M').length - 1).toBe(dark);
  });
});
